#!/usr/bin/env python3
"""Generate Lean 4 data files from GAP triangle group output.

Usage:
    gap -q compute_triangle_surfaces.g > /tmp/triangle.out
    python3 generate_triangle_lean.py /tmp/triangle.out
"""

import sys
import ast


def parse_gap_output(filename):
    """Parse the DATA_START..DATA_END block from GAP output."""
    data = {}
    in_data = False
    current_key = None
    current_val = ""

    with open(filename) as f:
        for line in f:
            line = line.strip()
            if line == "DATA_START":
                in_data = True
                continue
            if line == "DATA_END":
                if current_key:
                    data[current_key] = current_val
                break
            if not in_data:
                continue

            if "=" in line and not line.startswith(" "):
                # Save previous key
                if current_key:
                    data[current_key] = current_val
                key, val = line.split("=", 1)
                current_key = key.strip()
                current_val = val.strip()
            else:
                # Continuation line
                current_val += " " + line

    # Parse values
    result = {}
    for k, v in data.items():
        if k in ("name",):
            result[k] = v
        elif v.strip().startswith("["):
            # Parse GAP list: [ 1, 2, 3, ... ] or [ [1,2], [3], ... ]
            result[k] = ast.literal_eval(v)
        else:
            try:
                result[k] = int(v)
            except ValueError:
                result[k] = v

    return result


def emit_lean(data, outfile):
    """Emit a Lean 4 file with the triangle group data."""
    name = data["name"]
    nDarts = data["nDarts"]
    nV = data["nV"]
    nE = data["nE"]
    nF = data["nF"]
    r = data["r"]
    genus = (2 - (nV - nE + nF)) // 2

    prefix = name.lower()

    chunk_defs = []  # accumulate chunk definitions to emit before the main def

    def fmt_array(arr, fin_type, array_name):
        """Format array as Lean literal, using separate chunk defs for large arrays."""
        chunk_size = 500
        if len(arr) <= chunk_size:
            vals = ", ".join(str(x) for x in arr)
            return f"#[{vals}]"
        else:
            chunk_names = []
            for ci, i in enumerate(range(0, len(arr), chunk_size)):
                chunk = arr[i:i+chunk_size]
                vals = ", ".join(str(x) for x in chunk)
                cname = f"{array_name}_c{ci}"
                chunk_defs.append(f"private def {cname} : Array (Fin {fin_type}) := #[{vals}]")
                chunk_names.append(cname)
            # Use balanced binary tree of appends to avoid deep kernel recursion.
            # Flat "a ++ b ++ c ++ ..." gives depth N; balanced gives depth log₂(N).
            def balanced_append(names):
                if len(names) == 1:
                    return names[0]
                mid = len(names) // 2
                left = balanced_append(names[:mid])
                right = balanced_append(names[mid:])
                return f"({left} ++ {right})"
            return balanced_append(chunk_names)

    with open(outfile, "w") as f:
        f.write(f"""/-
Copyright (c) 2026 Robin Langer. All rights reserved.
Released under MIT license.

# {name} surface: triangle group data for Δ(2,3,{r})

Auto-generated by `generate_triangle_lean.py` from GAP computation.
{name} graph: {nV} vertices, {nE} edges, {nF} faces, genus {genus}.
{nDarts} darts = |G| group elements in the regular representation.
-/

import CSSCode.TriangleGroupSurface

set_option linter.style.longLine false
set_option linter.style.nativeDecide false
set_option linter.style.maxHeartbeats false

/-! ## Permutation data -/

""")

        def emit_array(f, var_name, arr, fin_type):
            """Emit chunk defs (if any) then the main array def."""
            chunk_defs.clear()
            val = fmt_array(arr, fin_type, var_name)
            for cd in chunk_defs:
                f.write(cd + "\n")
            if chunk_defs:
                f.write("\n")
            f.write(f"private def {var_name} : Array (Fin {fin_type}) :=\n  {val}\n\n")

        # R forward/inverse
        emit_array(f, f"{prefix}R_fwd", data['R_fwd'], nDarts)
        emit_array(f, f"{prefix}R_inv", data['R_inv'], nDarts)

        # S forward/inverse
        emit_array(f, f"{prefix}S_fwd", data['S_fwd'], nDarts)
        emit_array(f, f"{prefix}S_inv", data['S_inv'], nDarts)

        # Size proofs
        for arr_name in ["R_fwd", "R_inv", "S_fwd", "S_inv"]:
            f.write(f"private theorem {prefix}{arr_name}_size : {prefix}{arr_name}.size = {nDarts} := by native_decide\n")
        f.write("\n")

        # Coset maps
        f.write(f"/-! ## Coset projection maps -/\n\n")
        emit_array(f, f"{prefix}VertexOf_data", data['vertex_of'], nV)
        emit_array(f, f"{prefix}EdgeOf_data", data['edge_of'], nE)
        emit_array(f, f"{prefix}FaceOf_data", data['face_of'], nF)

        for arr_name, sz in [("VertexOf_data", nDarts), ("EdgeOf_data", nDarts), ("FaceOf_data", nDarts)]:
            f.write(f"private theorem {prefix}{arr_name}_size : {prefix}{arr_name}.size = {nDarts} := by native_decide\n")
        f.write("\n")

        # Coset representatives
        f.write(f"/-! ## Coset representatives -/\n\n")
        emit_array(f, f"{prefix}VertexRep_data", data['vertex_rep'], nDarts)
        emit_array(f, f"{prefix}EdgeRep_data", data['edge_rep'], nDarts)
        emit_array(f, f"{prefix}FaceRep_data", data['face_rep'], nDarts)

        for arr_name, sz in [("VertexRep_data", nV), ("EdgeRep_data", nE), ("FaceRep_data", nF)]:
            f.write(f"private theorem {prefix}{arr_name}_size : {prefix}{arr_name}.size = {sz} := by native_decide\n")
        f.write("\n")

        # TriangleGroupData instance
        f.write(f"""/-! ## TriangleGroupData instance -/

set_option maxHeartbeats 1600000 in
/-- Triangle group data for the {name} surface: Δ(2,3,{r}) acting on {nDarts} darts. -/
def {prefix}TriangleData : TriangleGroupData {nDarts} {nV} {nE} {nF} {r} where
  R := ⟨arrayToFin {prefix}R_fwd {prefix}R_fwd_size,
        arrayToFin {prefix}R_inv {prefix}R_inv_size,
        by native_decide, by native_decide⟩
  S := ⟨arrayToFin {prefix}S_fwd {prefix}S_fwd_size,
        arrayToFin {prefix}S_inv {prefix}S_inv_size,
        by native_decide, by native_decide⟩
  T_eq_RS := fun _ => rfl
  vertexOf := arrayToFin {prefix}VertexOf_data {prefix}VertexOf_data_size
  edgeOf := arrayToFin {prefix}EdgeOf_data {prefix}EdgeOf_data_size
  faceOf := arrayToFin {prefix}FaceOf_data {prefix}FaceOf_data_size
  vertexRep := arrayToFin {prefix}VertexRep_data {prefix}VertexRep_data_size
  edgeRep := arrayToFin {prefix}EdgeRep_data {prefix}EdgeRep_data_size
  faceRep := arrayToFin {prefix}FaceRep_data {prefix}FaceRep_data_size
  vertexOf_S := by native_decide
  vertexOf_rep := by native_decide
  edgeOf_T := by native_decide
  edgeOf_rep := by native_decide
  faceOf_R := by native_decide
  faceOf_rep := by native_decide
  edge_ne := by native_decide
  face_inj := by native_decide
  T_inv := by native_decide

set_option maxHeartbeats 1600000 in
/-- The {name} surface as a CellularSurface, constructed via Δ(2,3,{r}). -/
def {prefix}Surface : CellularSurface :=
  {prefix}TriangleData.toCellularSurface (by norm_num) (by native_decide)
""")

        # Sabidussi witness (if vertex-action generators are available)
        if "R_vertex_fwd" in data and "bfs_words" in data:
            f.write(f"\n/-! ## Sabidussi witness from vertex-action generators -/\n\n")

            # Vertex-action generators
            emit_array(f, f"{prefix}RV_fwd", data['R_vertex_fwd'], nV)
            emit_array(f, f"{prefix}RV_inv", data['R_vertex_inv'], nV)
            emit_array(f, f"{prefix}SV_fwd", data['S_vertex_fwd'], nV)
            emit_array(f, f"{prefix}SV_inv", data['S_vertex_inv'], nV)

            for arr_name in ["RV_fwd", "RV_inv", "SV_fwd", "SV_inv"]:
                f.write(f"private theorem {prefix}{arr_name}_size : {prefix}{arr_name}.size = {nV} := by native_decide\n")
            f.write("\n")

            # BFS witness words as a flat array of lists
            bfs_words = data['bfs_words']
            # Remap GAP BFS indices to match genOrInv convention.
            # GAP uses [R, R⁻¹, S, S⁻¹] = [0,1,2,3]
            # genOrInv with k=2 expects [gen0, gen1, gen0⁻¹, gen1⁻¹] = [R, S, R⁻¹, S⁻¹]
            # Mapping: GAP 0→0, 1→2, 2→1, 3→3
            gap_to_lean = {0: 0, 1: 2, 2: 1, 3: 3}
            word_strs = []
            for w in bfs_words:
                if len(w) == 0:
                    word_strs.append("[]")
                else:
                    remapped = [gap_to_lean[x] for x in w]
                    word_strs.append("[" + ", ".join(str(x) for x in remapped) + "]")

            # Write witness words as separate chunk defs then concatenate
            chunk_size = 200
            ww_chunk_names = []
            for ci, i in enumerate(range(0, len(word_strs), chunk_size)):
                chunk = word_strs[i:i+chunk_size]
                cname = f"{prefix}WW_c{ci}"
                f.write(f"private def {cname} : Array (List (Fin 4)) := #[{', '.join(chunk)}]\n")
                ww_chunk_names.append(cname)
            # Balanced binary tree of appends (avoid deep kernel recursion)
            def balanced_ww(names):
                if len(names) == 1:
                    return names[0]
                mid = len(names) // 2
                left = balanced_ww(names[:mid])
                right = balanced_ww(names[mid:])
                return f"({left} ++ {right})"
            f.write(f"\nprivate def {prefix}WitnessWords_data : Array (List (Fin 4)) :=\n")
            f.write(f"  {balanced_ww(ww_chunk_names)}\n\n")

            f.write(f"set_option maxHeartbeats 400000 in\n")
            f.write(f"private theorem {prefix}WitnessWords_data_size : {prefix}WitnessWords_data.size = {nV} := by native_decide\n\n")

            # The graph definition — we need to import it
            # For now, assume the graph is defined elsewhere and we reference it
            f.write(f"""/-! ## Sabidussi coset graph proof -/

/-- Vertex-action generators for the {name} graph. -/
def {prefix}VertexGens : Fin 2 → Equiv.Perm (Fin {nV})
  | 0 => ⟨arrayToFin {prefix}RV_fwd {prefix}RV_fwd_size,
          arrayToFin {prefix}RV_inv {prefix}RV_inv_size,
          by native_decide, by native_decide⟩
  | 1 => ⟨arrayToFin {prefix}SV_fwd {prefix}SV_fwd_size,
          arrayToFin {prefix}SV_inv {prefix}SV_inv_size,
          by native_decide, by native_decide⟩

/-- BFS witness words mapping vertex 0 to every other vertex. -/
def {prefix}Witness (v : Fin {nV}) : List (Fin 4) :=
  {prefix}WitnessWords_data[v.val]'(by have h := {prefix}WitnessWords_data_size; omega)
""")

        # Dart-level left multiplication permutations (for algebraic Sabidussi)
        if "LR_fwd" in data:
            f.write(f"\n/-! ## Dart-level left multiplication (for algebraic Sabidussi proof) -/\n\n")

            emit_array(f, f"{prefix}LR_fwd", data['LR_fwd'], nDarts)
            emit_array(f, f"{prefix}LR_inv", data['LR_inv'], nDarts)
            emit_array(f, f"{prefix}LS_fwd", data['LS_fwd'], nDarts)
            emit_array(f, f"{prefix}LS_inv", data['LS_inv'], nDarts)

            for arr_name in ["LR_fwd", "LR_inv", "LS_fwd", "LS_inv"]:
                f.write(f"private theorem {prefix}{arr_name}_size : {prefix}{arr_name}.size = {nDarts} := by native_decide\n")
            f.write("\n")

            f.write(f"""/-- Left multiplication by R on darts. -/
def {prefix}DartGenR : Equiv.Perm (Fin {nDarts}) :=
  ⟨arrayToFin {prefix}LR_fwd {prefix}LR_fwd_size,
   arrayToFin {prefix}LR_inv {prefix}LR_inv_size,
   by native_decide, by native_decide⟩

/-- Left multiplication by S on darts. -/
def {prefix}DartGenS : Equiv.Perm (Fin {nDarts}) :=
  ⟨arrayToFin {prefix}LS_fwd {prefix}LS_fwd_size,
   arrayToFin {prefix}LS_inv {prefix}LS_inv_size,
   by native_decide, by native_decide⟩
""")

    print(f"Generated {outfile}: {name}, {nDarts} darts, genus {genus}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python3 generate_triangle_lean.py <gap_output_file> [output.lean]")
        sys.exit(1)

    data = parse_gap_output(sys.argv[1])
    outfile = sys.argv[2] if len(sys.argv) > 2 else f"CSSCode/{data['name']}TriangleData.lean"
    emit_lean(data, outfile)
