#!/usr/bin/env python3
"""
Generate a Lean 4 CellularSurface instance from cellular_surfaces_data.json.

Uses Array-backed data instead of ![...] vector notation to avoid
elaborator crashes on large instances (>100 edges).

Usage:
    python3 generate_lean_surface.py clayworth   # generates CSSCode/ClayworthSurface.lean
    python3 generate_lean_surface.py klein       # generates CSSCode/KleinSurface.lean
"""

import json
import sys
import os

JSON_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "cellular_surfaces_data.json")

# Map JSON keys to Lean file metadata
SURFACE_META = {
    "bolza": {
        "lean_name": "BolzaSurface",
        "lean_file": "CSSCode/BolzaSurface.lean",
        "doc_name": "Bolza Surface (Möbius-Kantor, F016A)",
        "description": "Möbius-Kantor graph on the Bolza surface (genus 2).",
    },
    "klein": {
        "lean_name": "KleinSurface",
        "lean_file": "CSSCode/KleinSurface.lean",
        "doc_name": "Klein Quartic (F056A)",
        "description": "Klein quartic {7,3} tiling (genus 3, PSL(2,7)).",
    },
    "clayworth": {
        "lean_name": "ClayworthSurface",
        "lean_file": "CSSCode/ClayworthSurface.lean",
        "doc_name": "Clayworth Surface (G₂(2)/C₃)",
        "description": "Clayworth {12,3} tiling of genus 505, from Sab(G₂(2), C₃).",
    },
}


CHUNK_SIZE = 500  # Max elements per #[...] literal (stay under maxRecDepth 1024)


def format_array(values, per_line=20):
    """Format a list of values as a Lean #[...] array literal."""
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i+per_line]
        lines.append("    " + ", ".join(str(v) for v in chunk))
    return "#[\n" + ",\n".join(lines) + "\n  ]"


def format_chunked_array(name, values, type_str, per_line=20):
    """Format a large array as concatenation of smaller chunks.
    Returns list of Lean definition strings."""
    if len(values) <= CHUNK_SIZE:
        return [f"private def {name} : Array {type_str} :=\n  {format_array(values, per_line)}"]

    defs = []
    chunks = []
    for ci in range(0, len(values), CHUNK_SIZE):
        chunk_vals = values[ci:ci+CHUNK_SIZE]
        chunk_name = f"{name}_chunk{ci // CHUNK_SIZE}"
        chunks.append(chunk_name)
        defs.append(f"private def {chunk_name} : Array {type_str} :=\n  {format_array(chunk_vals, per_line)}")

    # Build the concatenation
    concat_expr = " ++ ".join(chunks)
    defs.append(f"private def {name} : Array {type_str} :=\n  {concat_expr}")
    return defs


def generate_lean(key, data, meta):
    """Generate the Lean 4 file content."""
    nV = data["vertices"]
    nE = data["edges"]
    nF = data["faces"]
    face_size = data["face_size"]
    genus = data["genus"]

    edge_src = data["edge_src"]
    edge_tgt = data["edge_tgt"]
    face_edge = data["face_edge"]
    face_dir = data["face_dir"]

    # Flatten face data: face_edge is nF × face_size, flatten to nF * face_size
    flat_face_edge = []
    flat_face_dir = []
    for f in range(nF):
        for i in range(face_size):
            flat_face_edge.append(face_edge[f][i])
            flat_face_dir.append(face_dir[f][i])

    lean_name = meta["lean_name"]
    doc_name = meta["doc_name"]
    description = meta["description"]

    lines = []
    lines.append(f"""/-
Copyright (c) 2026 Robin Langer. All rights reserved.
Released under MIT license.

# {doc_name}: Array-backed CellularSurface

{description}

This file is auto-generated by `generate_lean_surface.py` from
`cellular_surfaces_data.json`. It uses Array-backed data to avoid
the elaborator crash caused by `![...]` on large vectors.

  - V = {nV}, E = {nE}, F = {nF}
  - Face size = {face_size} ({"dodecagonal" if face_size == 12 else f"{face_size}-gonal"})
  - Genus = {genus}
  - χ = {nV} - {nE} + {nF} = {nV - nE + nF} = 2 - 2 × {genus}
-/

import CSSCode.CellularSurface

/-! ## Array-backed lookup

  We store edge/face data in `Array` literals (flat memory, O(1) lookup)
  rather than `![...]` vectors (nested `Fin.cons`, O(n) elaboration depth).
  A helper converts `Array` + size proof → `Fin n → α`. -/

/-- Convert an Array to a function on Fin, given a proof that the array has
    the right size. Uses `a[i]'h` for O(1) lookup. -/
def arrayToFin (a : Array α) (h : a.size = n) (i : Fin n) : α :=
  a[i.val]'(by omega)

/-! ## Raw data arrays -/
""")

    # Edge source array
    for d in format_chunked_array(f"{lean_name}_edge_src_data", edge_src, f"(Fin {nV})"):
        lines.append(d)
        lines.append("")

    # Edge target array
    for d in format_chunked_array(f"{lean_name}_edge_tgt_data", edge_tgt, f"(Fin {nV})"):
        lines.append(d)
        lines.append("")

    # Face edge array (flat: index = f * face_size + i)
    for d in format_chunked_array(f"{lean_name}_face_edge_data", flat_face_edge, f"(Fin {nE})"):
        lines.append(d)
        lines.append("")

    # Face dir array (flat: same indexing)
    dir_strs = ["true" if d else "false" for d in flat_face_dir]
    for d in format_chunked_array(f"{lean_name}_face_dir_data", dir_strs, "Bool"):
        lines.append(d)
        lines.append("")

    # Size proofs
    lines.append("/-! ## Size proofs (verified by native_decide) -/")
    lines.append("")
    lines.append(f"private theorem {lean_name}_edge_src_size :")
    lines.append(f"    {lean_name}_edge_src_data.size = {nE} := by native_decide")
    lines.append("")
    lines.append(f"private theorem {lean_name}_edge_tgt_size :")
    lines.append(f"    {lean_name}_edge_tgt_data.size = {nE} := by native_decide")
    lines.append("")
    lines.append(f"private theorem {lean_name}_face_edge_size :")
    lines.append(f"    {lean_name}_face_edge_data.size = {nF * face_size} := by native_decide")
    lines.append("")
    lines.append(f"private theorem {lean_name}_face_dir_size :")
    lines.append(f"    {lean_name}_face_dir_data.size = {nF * face_size} := by native_decide")
    lines.append("")

    # The CellularSurface instance
    lines.append("/-! ## The CellularSurface instance -/")
    lines.append("")
    lines.append(f"/-- The {doc_name} as a CellularSurface.")
    lines.append(f"    {nV} vertices, {nE} edges, {nF} faces of size {face_size}, genus {genus}. -/")
    lines.append(f"def {lean_name[0].lower() + lean_name[1:]} : CellularSurface where")
    lines.append(f"  nV := {nV}")
    lines.append(f"  nE := {nE}")
    lines.append(f"  nF := {nF}")
    lines.append(f"  edge_src := arrayToFin {lean_name}_edge_src_data {lean_name}_edge_src_size")
    lines.append(f"  edge_tgt := arrayToFin {lean_name}_edge_tgt_data {lean_name}_edge_tgt_size")
    lines.append(f"  edge_ne := by native_decide")
    lines.append(f"  face_len := fun _ => {face_size}")
    lines.append(f"  face_len_pos := fun _ => by norm_num")
    lines.append(f"  face_edge := fun f i =>\n"
                 f"    have := {lean_name}_face_edge_size\n"
                 f"    {lean_name}_face_edge_data[f.val * {face_size} + i.val]'(by omega)")
    lines.append(f"  face_dir := fun f i =>\n"
                 f"    have := {lean_name}_face_dir_size\n"
                 f"    {lean_name}_face_dir_data[f.val * {face_size} + i.val]'(by omega)")
    lines.append(f"  face_inj := by native_decide")
    lines.append(f"  face_closed := by native_decide")
    lines.append("")

    # Euler characteristic
    lines.append(f"/-- Euler characteristic confirms genus {genus}. -/")
    lines.append(f"theorem {lean_name[0].lower() + lean_name[1:]}_euler :")
    lines.append(f"    ({nV} : ℤ) - {nE} + {nF} = 2 - 2 * {genus} := by norm_num")
    lines.append("")

    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 generate_lean_surface.py <surface_key>")
        print(f"Available: {', '.join(SURFACE_META.keys())}")
        sys.exit(1)

    key = sys.argv[1].lower()
    if key not in SURFACE_META:
        print(f"Unknown surface: {key}")
        print(f"Available: {', '.join(SURFACE_META.keys())}")
        sys.exit(1)

    with open(JSON_PATH) as f:
        all_data = json.load(f)

    if key not in all_data:
        print(f"Surface '{key}' not in {JSON_PATH}")
        sys.exit(1)

    data = all_data[key]
    meta = SURFACE_META[key]

    lean_content = generate_lean(key, data, meta)

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            meta["lean_file"])
    with open(out_path, "w") as f:
        f.write(lean_content)

    print(f"Generated {out_path}")
    print(f"  V={data['vertices']}, E={data['edges']}, F={data['faces']}, "
          f"genus={data['genus']}")


if __name__ == "__main__":
    main()
