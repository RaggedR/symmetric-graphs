# The real approach: compute the character of the permutation
# representation restricted to each eigenspace
# ============================================================

def analyze_eigenspace_irreducibility(adj_list, name, group_order):
    """
    For each eigenspace E_λ of A, the permutation representation ρ of Aut(G)
    restricts to a representation on E_λ. We want to know if this restriction
    is irreducible.

    Key insight: We don't need explicit group generators!
    The adjacency matrix A commutes with all ρ(g), so A acts as a SCALAR
    on each irreducible component (Schur's lemma). Therefore:

    - If an eigenspace is irreducible under Aut(G) → A has a simple eigenvalue there ✓
    - If an eigenspace decomposes as V_i ⊕ V_j under a SUBGROUP H < Aut(G) where
      V_i and V_j are non-isomorphic H-irreps → H cannot "see" the extra symmetry

    The real test: compute A², A³, etc. restricted to the eigenspace.
    If the algebra generated by {A|_E} is the FULL matrix algebra M_d(R),
    then the commutant is {scalars} = the eigenspace is irreducible under Aut(G).

    But if the commutant is larger → the eigenspace is reducible.

    Actually, the cleanest approach:
    The COMMUTANT of Aut(G) in End(R^n) is the algebra generated by A
    (for vertex-transitive graphs, by the Bose-Mesner algebra of the
    association scheme).

    For a distance-transitive graph (like F056A), the association scheme
    is generated by A, and the eigenspaces are exactly the irreducible
    components of the permutation representation.
    """
    A = build_adjacency_matrix(adj_list)
    n = A.shape[0]

    eigenvalues, eigenvectors = np.linalg.eigh(A)
    eigenvalues_rounded = np.round(eigenvalues, 6)
    unique_evals = sorted(set(eigenvalues_rounded), reverse=True)

    print(f"\n{'═' * 60}")
    print(f"  {name}")
    print(f"  n = {n}")
    print(f"{'═' * 60}")

    # Compute the distance matrices D_0, D_1, ..., D_d
    # D_k[i,j] = 1 iff dist(i,j) = k
    # For a distance-regular graph, {D_0, D_1, ..., D_d} spans an algebra
    # (the Bose-Mesner algebra) whose dimension = d+1 = number of distinct eigenvalues

    # Compute distance matrix
    from collections import deque
    dist_matrix = np.full((n, n), -1, dtype=int)
    for start in range(n):
        dist_matrix[start, start] = 0
        q = deque([start])
        while q:
            v = q.popleft()
            for u_1indexed in adj_list[v]:
                u = u_1indexed - 1
                if dist_matrix[start, u] == -1:
                    dist_matrix[start, u] = dist_matrix[start, v] + 1
                    q.append(u)

    diameter = dist_matrix.max()
    print(f"\n  Diameter: {diameter}")
    print(f"  Distinct eigenvalues: {len(unique_evals)}")

    # Check distance-regularity: for each distance k, the intersection numbers
    # a_k, b_k, c_k should be constant
    is_dist_regular = True
    intersection_array = []

    for k in range(diameter + 1):
        D_k = (dist_matrix == k).astype(float)

        # For vertex-transitive graph, just check from vertex 0
        v = 0
        nbrs_at_k = np.where(dist_matrix[v] == k)[0]
        if len(nbrs_at_k) == 0:
            continue

        # For each vertex u at distance k from v, count:
        # c_k = |{w : d(v,w)=k-1, d(u,w)=1}| (should be constant)
        # a_k = |{w : d(v,w)=k, d(u,w)=1}|
        # b_k = |{w : d(v,w)=k+1, d(u,w)=1}|

        c_vals, a_vals, b_vals = [], [], []
        for u in nbrs_at_k:
            u_nbrs = set(j - 1 for j in adj_list[u])
            c = len([w for w in u_nbrs if dist_matrix[v, w] == k - 1]) if k > 0 else 0
            a = len([w for w in u_nbrs if dist_matrix[v, w] == k])
            b = len([w for w in u_nbrs if dist_matrix[v, w] == k + 1]) if k < diameter else 0
            c_vals.append(c)
            a_vals.append(a)
            b_vals.append(b)

        if len(set(c_vals)) > 1 or len(set(a_vals)) > 1 or len(set(b_vals)) > 1:
            is_dist_regular = False
            break
        intersection_array.append((c_vals[0], a_vals[0], b_vals[0]))

    if is_dist_regular:
        print(f"  Distance-regular: YES")
        print(f"  Intersection array: {{", end="")
        print(", ".join(str(b) for _, _, b in intersection_array[:-1]), end="")
        print(f"; {', '.join(str(c) for c, _, _ in intersection_array[1:])}}}")
        print(f"\n  ★ CONSEQUENCE: Distance-regular ⟹ each eigenspace is")
        print(f"    an IRREDUCIBLE representation of Aut(G).")
        print(f"    (The Bose-Mesner algebra = full commutant of Aut(G))")
    else:
        print(f"  Distance-regular: NO")
        print(f"\n  Need to check irreducibility by other means.")

        # For non-distance-regular: check if the adjacency algebra
        # (generated by powers of A) separates the eigenspaces fully
        # i.e., dim(span{I, A, A², ...}) = number of distinct eigenvalues

        powers = [np.eye(n)]
        for p in range(1, n):
            powers.append(powers[-1] @ A)
            # Check rank of the span
            mat = np.array([M.flatten() for M in powers])
            rank = np.linalg.matrix_rank(mat, tol=1e-8)
            if rank == len(unique_evals):
                print(f"  Adjacency algebra dimension: {rank} (generated by A^0, ..., A^{p})")
                print(f"  Equals number of distinct eigenvalues: {len(unique_evals)}")
                print(f"  ★ CONSEQUENCE: Adjacency algebra is maximal commutative in")
                print(f"    the commutant of Aut(G). Each eigenspace is either:")
                print(f"    (a) an irrep of Aut(G), OR")
                print(f"    (b) a sum of ISOMORPHIC irreps (multiplicity-free impossible)")
                break

    # Now the key comparison: eigenspaces vs irreps of the SURFACE group
    # vs irreps of the FULL graph automorphism group
    print(f"\n  Eigenspace dimensions:")
    for ev in unique_evals:
        mult = list(eigenvalues_rounded).count(ev)
        print(f"    λ = {ev:10.6f}  dim = {mult}")

    return is_dist_regular, unique_evals, diameter


