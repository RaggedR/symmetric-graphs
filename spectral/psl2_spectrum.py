def adj_to_matrix(n, adj):
    """Convert 1-indexed adjacency list to numpy adjacency matrix."""
    A = np.zeros((n, n))
    for i, neighbours in enumerate(adj):
        for j in neighbours:
            A[i][j - 1] = 1.0
    return A


def compute_girth(adj):
    """BFS-based girth computation."""
    n = len(adj)
    girth = float('inf')
    for start in range(n):
        dist = [-1] * n
        dist[start] = 0
        queue = [start]
        head = 0
        while head < len(queue):
            v = queue[head]; head += 1
            for w in adj[v]:
                w0 = w - 1
                if dist[w0] == -1:
                    dist[w0] = dist[v] + 1
                    queue.append(w0)
                elif dist[w0] >= dist[v]:
                    girth = min(girth, dist[v] + dist[w0] + 1)
        if girth <= 3:
            break
    return girth


def identify_algebraic(val, tol=1e-5):
    """
    Try to express val as a recognisable algebraic number.
    Returns a unicode string or None.
    """
    # Check small integers first
    for n in range(-6, 7):
        if abs(val - n) < tol:
            return str(n)

    # Check simple fractions (small numerator, small denominator)
    for den in range(2, 8):
        for num in range(-6 * den, 6 * den + 1):
            if math.gcd(abs(num), den) == 1 and abs(val - num / den) < tol:
                return f"{num}/{den}"

    # Check n ± √m / d for small integers m, d
    for sq in range(2, 10):
        if math.isqrt(sq) ** 2 == sq:
            continue   # skip perfect squares — already caught above
        root = math.sqrt(sq)
        for num in range(-6, 7):
            for den in (1, 2):
                for sign in (1, -1):
                    candidate = (num + sign * root) / den
                    if abs(val - candidate) < tol:
                        minus = sign < 0
                        sq_s = f"√{sq}"
                        if num == 0:
                            prefix = "−" if minus else ""
                            base = f"{prefix}{sq_s}"
                        else:
                            s = "−" if minus else "+"
                            base = f"({num}{s}{sq_s})"
                        return base if den == 1 else f"{base}/{den}"
    return None


def analyse(name, q, H, n, adj, girth_hint=None):
    """Full spectral analysis of one graph."""
    A = adj_to_matrix(n, adj)
    eigs = np.sort(eigvalsh(A))[::-1]

    # Cluster into distinct eigenvalues
    unique = []
    for e in eigs:
        if not any(abs(e - u) < 1e-7 for u in unique):
            unique.append(e)
    unique.sort(reverse=True)

    multiplicities = []
    for u in unique:
        m = sum(1 for e in eigs if abs(e - u) < 1e-7)
        multiplicities.append((u, m))

    lambda1  = eigs[0]
    lambda2  = eigs[1]
    lam_min  = eigs[-1]
    # Laplacian eigenvalues = 3 - adj_eigs (sorted ascending)
    lap_eigs = np.sort(3.0 - eigs)
    fiedler  = lap_eigs[1]
    gap      = lambda1 - lambda2

    ramanujan_bound = 2.0 * math.sqrt(2)
    is_ram = lambda2 <= ramanujan_bound + 1e-9

    girth = girth_hint if girth_hint is not None else compute_girth(adj)

    # Identify algebraic form of each eigenvalue
    alg = []
    for u, m in multiplicities:
        s = identify_algebraic(u)
        alg.append(s)

    return {
        'name'       : name,
        'q'          : q,
        'H'          : H,
        'n'          : n,
        'girth'      : girth,
        'lambda2'    : lambda2,
        'lam_min'    : lam_min,
        'fiedler'    : fiedler,
        'gap'        : gap,
        'is_ram'     : is_ram,
        'n_eigs'     : len(unique),
        'spectrum'   : multiplicities,
        'alg_names'  : alg,
    }


