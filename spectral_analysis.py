"""
Spectral analysis of cubic arc-transitive graphs from PSL(2, q) = SU(2, F_q)/{±I}.

Computes adjacency spectrum and Fiedler eigenvalue (algebraic connectivity)
for each graph in the A1 family.
"""

import numpy as np
from numpy.linalg import eigvalsh

def adj_to_matrix(n, adj):
    """Convert adjacency list (1-indexed) to numpy matrix."""
    A = np.zeros((n, n))
    for i in range(n):
        for j in adj[i]:
            A[i][j - 1] = 1
    return A

def spectral_analysis(name, n, adj):
    """Compute and display spectral properties."""
    A = adj_to_matrix(n, adj)

    # Adjacency eigenvalues (sorted descending)
    adj_eigs = np.sort(eigvalsh(A))[::-1]

    # Laplacian L = D - A; for 3-regular: L = 3I - A
    lap_eigs = 3 - adj_eigs  # sorted ascending
    lap_eigs = np.sort(lap_eigs)

    # Key spectral quantities
    lambda1 = adj_eigs[0]       # largest adjacency eigenvalue (should be 3)
    lambda2 = adj_eigs[1]       # second largest adjacency eigenvalue
    lambda_min = adj_eigs[-1]   # smallest adjacency eigenvalue
    fiedler = lap_eigs[1]       # algebraic connectivity
    spectral_gap = lambda1 - lambda2

    # Ramanujan bound: for a k-regular graph, λ₂ ≤ 2√(k-1)
    ramanujan_bound = 2 * np.sqrt(2)  # ≈ 2.828 for k=3
    is_ramanujan = lambda2 <= ramanujan_bound + 1e-10

    # Count distinct eigenvalues (up to tolerance)
    unique_eigs = []
    for e in adj_eigs:
        if not any(abs(e - u) < 1e-8 for u in unique_eigs):
            unique_eigs.append(e)

    # Eigenvalue multiplicities
    mults = []
    for u in sorted(unique_eigs, reverse=True):
        m = sum(1 for e in adj_eigs if abs(e - u) < 1e-8)
        mults.append((u, m))

    print(f"\n{'='*70}")
    print(f"  {name}   ({n} vertices, cubic)")
    print(f"{'='*70}")
    print(f"  Adjacency spectrum ({len(unique_eigs)} distinct eigenvalues):")
    for val, mult in mults:
        marker = ""
        if abs(val - 3) < 1e-8:
            marker = "  <-- k"
        elif mult == mults[1][1] and abs(val - mults[1][0]) < 1e-8:
            marker = "  <-- λ₂"
        print(f"    {val:+10.6f}  (multiplicity {mult}){marker}")
    print(f"\n  λ₁ = {lambda1:.6f} (= k = 3)")
    print(f"  λ₂ = {lambda2:.6f}")
    print(f"  λ_min = {lambda_min:.6f}")
    print(f"  Spectral gap (λ₁ - λ₂) = {spectral_gap:.6f}")
    print(f"  Fiedler eigenvalue = {fiedler:.6f}")
    print(f"  Ramanujan bound 2√(k-1) = {ramanujan_bound:.6f}")
    print(f"  Ramanujan? {is_ramanujan}")

    return {
        'name': name, 'n': n, 'lambda2': lambda2,
        'fiedler': fiedler, 'spectral_gap': spectral_gap,
        'lambda_min': lambda_min, 'is_ramanujan': is_ramanujan,
        'n_distinct': len(unique_eigs)
    }


